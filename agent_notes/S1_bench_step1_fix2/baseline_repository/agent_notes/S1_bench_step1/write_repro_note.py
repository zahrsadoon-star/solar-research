"""Generate the accepted cross-platform drift note from archived keyed differences."""
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent


def main() -> None:
    """Report dimensionless metric drift; rank shifts are positions, timing excluded."""
    frame = pd.read_csv(HERE / 'windows_rerun/preservation_differences.csv')
    if frame.duplicated(['site', 'h', 'algorithm', 'metric']).any():
        raise ValueError('Duplicate comparison keys')
    frame['absolute'] = (frame.after-frame.before).abs()
    lines = ['# S1 Linux/Windows reproducibility note', '',
        'Lead decision, 29 October 2026: published main results were produced in a Linux '
        'cloud session; the archived rerun was produced on Windows. Treat the observed '
        'drift as cross-platform numerical variability. This is the accepted interpretation, '
        'not a causally isolated platform experiment. No settings were changed and no '
        'additional model runs were made to recover agreement.', '',
        'Generated by `python agent_notes/S1_bench_step1/write_repro_note.py` from '
        '`windows_rerun/preservation_differences.csv`, keyed by site, horizon, algorithm '
        'and metric. Differences are at stored metric precision. Runtime is excluded.', '',
        f'Changed metric/rank cells: {len(frame)}.', '',
        '| Metric | Maximum absolute difference |', '|---|---:|']
    for metric, g in frame.groupby('metric'):
        lines.append(f'| {metric} | {g.absolute.max():.4f} |')
    lines += ['', '| Algorithm with any metric or rank drift | Maximum Brier difference | Maximum rank change |',
              '|---|---:|---:|']
    for algorithm, g in frame.groupby('algorithm'):
        bs = g.loc[g.metric.eq('brier'), 'absolute'].max()
        rank = g.loc[g.metric.eq('rank_by_brier'), 'absolute'].max()
        lines.append(f'| {algorithm} | {0 if pd.isna(bs) else bs:.4f} | {0 if pd.isna(rank) else rank:.0f} |')
    lines += ['', 'The largest Brier drift is concentrated in XGBoost and Gradient Boosting. '
        'Other algorithms listed above have smaller metric changes or rank changes caused '
        'by reordered competitors. A zero in this table means no changed stored cell for '
        'that metric, not proven bitwise equality of predictions.', '',
        'The Windows predictions and rerun score files are archived under windows_rerun/. '
        'They are not inputs to the independent significance check. That check reads only '
        'main\'s original-run hourly_predictions_top6.csv.gz. Earlier preservation-gate notes '
        'describe the superseded lead decision; they must not be read as a current blocker.', '']
    (HERE / 'REPRO_NOTE.md').write_text('\n'.join(lines), encoding='utf-8')


if __name__ == '__main__':
    main()
